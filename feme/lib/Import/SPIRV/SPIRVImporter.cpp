llvm::Expected<Module> SPIRVImporter::import(llvm::MemoryBufferRef Buffer,
                                             const ImportOptions &Opts,
                                             Context &Ctx) const {
  // SPIR-V binaries are a stream of 32-bit words (see the SPIR-V
  // specification); reject inputs that cannot possibly be one rather than
  // reading past the end of the buffer.
  if (Buffer.getBufferSize() % sizeof(uint32_t) != 0)
    return llvm::createStringError(
        llvm::inconvertibleErrorCode(),
        "SPIR-V binary module must contain an integral number of 32-bit "
        "words");

  mlir::MLIRContext &MLIRCtx = Ctx.getMLIRContext();
  MLIRCtx.loadDialect<mlir::spirv::SPIRVDialect>();

  // `Buffer.getBufferStart()` has no alignment guarantee at all (it may
  // point into a `std::string`/string-literal-backed `StringRef`, neither
  // of which promises 4-byte alignment) -- reinterpret_cast'ing it
  // directly to `const uint32_t *` and reading through that pointer is
  // undefined behavior on a target where an unaligned load actually
  // traps (confirmed by a real UBSan `RejectsMalformedBinary` failure:
  // "load of misaligned address ... for type 'const unsigned int *'").
  // `llvm::support::endian::read32<native>` performs the same load via an
  // unaligned-safe memcpy under the hood, so copying every word through
  // it into a `SmallVector<uint32_t>` (whose own allocation is
  // word-aligned) is both portable and gives `stripNonSemanticExtInst`
  // the same word-array view it already expects.
  size_t WordCount = Buffer.getBufferSize() / sizeof(uint32_t);
  llvm::SmallVector<uint32_t> RawWords;
  RawWords.reserve(WordCount);
  const char *Data = Buffer.getBufferStart();
  for (size_t I = 0; I != WordCount; ++I)
    RawWords.push_back(llvm::support::endian::read32<llvm::endianness::native>(
        Data + I * sizeof(uint32_t)));
  llvm::SmallVector<uint32_t> Filtered = stripNonSemanticExtInst(RawWords);
  Filtered = lowerProjectiveImageSamples(Filtered);
  Filtered = lowerImageQueryOpcodes(Filtered);
  Filtered = disambiguateDuplicateStructNames(Filtered);
  llvm::ArrayRef<uint32_t> Binary = Filtered;

  mlir::spirv::DeserializationOptions DeserOpts;
  DeserOpts.enableControlFlowStructurization =
      Opts.SPIRVEnableControlFlowStructurization;

  bool MayRetry = DeserOpts.enableControlFlowStructurization &&
                  Opts.SPIRVFallBackToUnstructuredControlFlow;

  mlir::OwningOpRef<mlir::spirv::ModuleOp> SpirvModule;
  {
    // Only the *final* attempt's diagnostics should reach the caller: a
    // structurization failure that the retry below recovers from is not an
    // error the user needs to hear about.
    mlir::ScopedDiagnosticHandler Swallow(
        &MLIRCtx, [MayRetry](mlir::Diagnostic &) {
          return MayRetry ? mlir::success() : mlir::failure();
        });
    SpirvModule = mlir::spirv::deserialize(Binary, &MLIRCtx, DeserOpts);
  }

  if (!SpirvModule && MayRetry) {
    DeserOpts.enableControlFlowStructurization = false;
    SpirvModule = mlir::spirv::deserialize(Binary, &MLIRCtx, DeserOpts);
  }

  if (!SpirvModule)
    return llvm::createStringError(llvm::inconvertibleErrorCode(),
                                   "failed to deserialize SPIR-V module");

  return Module::fromMLIR(std::move(SpirvModule));
}

llvm::StringRef SPIRVImporter::getFormatName() const { return "spirv"; }
