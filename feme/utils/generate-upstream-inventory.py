#!/usr/bin/env python3
"""Generate feme/docs/UpstreamInventory.md from the feme branch history."""

import argparse
import collections
import pathlib
import subprocess
import sys


COMMIT_MARKER = "@@UPSTREAM_INVENTORY_COMMIT@@"
EXCLUDED_FILES = {"agent_prompt.md", "agent_thoughts.md"}
EXCLUDED_COMMIT_PATHS = {"ubsan-errors.txt"}
REPOSITORY_ROOT = pathlib.Path(__file__).resolve().parents[2]
DEFAULT_OUTPUT = REPOSITORY_ROOT / "feme" / "docs" / "UpstreamInventory.md"


def parse_args(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source",
        default="cbieneman/feme",
        help="branch containing the changes to inventory (default: %(default)s)",
    )
    parser.add_argument(
        "--base",
        default="origin/main",
        help="base ref whose reachable commits are excluded (default: %(default)s)",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=pathlib.Path,
        default=DEFAULT_OUTPUT,
        help="output Markdown file (default: feme/docs/UpstreamInventory.md)",
    )
    return parser.parse_args(argv)


def git_log(source, base):
    command = [
        "git",
        "log",
        "--reverse",
        "-m",
        "--format=" + COMMIT_MARKER + "%H%x09%P%x09%s",
        "--name-only",
        source,
        "--not",
        base,
    ]
    try:
        return subprocess.run(
            command,
            cwd=REPOSITORY_ROOT,
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        ).stdout
    except subprocess.CalledProcessError as error:
        sys.stderr.write(error.stderr)
        raise SystemExit(error.returncode)


def collect_commits(log):
    commits = collections.OrderedDict()
    current = None

    for line in log.splitlines():
        if line.startswith(COMMIT_MARKER):
            commit_hash, parents, subject = line[len(COMMIT_MARKER):].split("\t", 2)
            current = commits.setdefault(
                commit_hash,
                {"subject": subject, "parents": parents.split(), "paths": set()},
            )
        elif line and current is not None:
            current["paths"].add(line)

    return commits


def is_main_merge(commit, base):
    parents = commit["parents"]
    if len(parents) < 2:
        return False

    for parent in parents[1:]:
        result = subprocess.run(
            ["git", "merge-base", "--is-ancestor", parent, base],
            cwd=REPOSITORY_ROOT,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
        if result.returncode == 1:
            return False
        if result.returncode != 0:
            sys.stderr.write(result.stderr)
            raise SystemExit(result.returncode)

    return True


def group_commits(commits):
    groups = collections.defaultdict(list)

    for commit_hash, commit in commits.items():
        paths = commit["paths"]
        if paths & EXCLUDED_COMMIT_PATHS:
            continue

        directories = set()
        for path in paths:
            parts = pathlib.PurePosixPath(path).parts
            if not parts or parts[0] == "feme" or parts[-1] in EXCLUDED_FILES:
                continue
            directories.add(parts[0] if len(parts) > 1 else None)

        for directory in directories:
            groups[directory].append((commit_hash, commit["subject"]))

    return groups


def escape_table_cell(text):
    return text.replace("\\", "\\\\").replace("|", "\\|")


def render(source, base, groups):
    lines = [
        "<!-- Generated by feme/utils/generate-upstream-inventory.py. -->",
        "",
        "# Upstream Change Inventory",
        "",
        f"This inventory lists commits reachable from `{source}` but not from",
        f"`{base}` that modify files outside `feme/`. Changes to `agent_prompt.md`",
        "and `agent_thoughts.md`, and commits that modify `ubsan-errors.txt`, are",
        "excluded, as are merge commits whose non-first parents are all reachable",
        f"from `{base}`. Commits are grouped by the top-level directory containing the",
        "qualifying changes and are ordered from oldest to newest within each group.",
    ]

    for directory in sorted(groups, key=lambda value: (value is None, value or "")):
        heading = "Repository root" if directory is None else f"`{directory}/`"
        lines.extend(
            [
                "",
                f"## {heading}",
                "",
                "| Git hash | Description |",
                "| --- | --- |",
            ]
        )
        for commit_hash, subject in groups[directory]:
            lines.append(f"| `{commit_hash}` | {escape_table_cell(subject)} |")

    return "\n".join(lines) + "\n"


def main(argv):
    args = parse_args(argv)
    commits = collect_commits(git_log(args.source, args.base))
    commits = {
        commit_hash: commit
        for commit_hash, commit in commits.items()
        if not is_main_merge(commit, args.base)
    }
    output = render(args.source, args.base, group_commits(commits))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))